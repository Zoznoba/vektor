async def run(apply: bool) -> None:
    async with async_session_factory() as session:
        rows = (
            await session.execute(
                sa.text(
                    """
                    SELECT q.id, q.text, q.self_text
                    FROM questions q
                    JOIN questionnaire_versions v ON v.id = q.version_id
                    WHERE v.is_current OR v.status = 'draft'
                    ORDER BY q.id
                    """
                )
            )
        ).all()

        matched = 0
        skipped = 0
        unmatched: list[str] = []
        for qid, text, current_self in rows:
            want = SELF_TEXT.get(text)
            if want is None:
                unmatched.append(text)
                continue
            if current_self == want:
                skipped += 1
                continue
            matched += 1
            if apply:
                await session.execute(
                    sa.text("UPDATE questions SET self_text = :s WHERE id = :i"),
                    {"s": want, "i": qid},
                )

        if apply:
            await session.commit()

    print(f"Вопросов (действующая редакция + черновик): {len(rows)}")
    print(f"{'Обновлено' if apply else 'Будет обновлено'}: {matched}")
    print(f"Уже с нужным self_text: {skipped}")
    if unmatched:
        print(f"Без формулировки самооценки ({len(unmatched)}):")
        for text in unmatched:
            print(f"  — {text}")
    if not apply:
        print("\nDry-run. Повторите с --apply, чтобы записать.")


if __name__ == "__main__":
    asyncio.run(run(apply="--apply" in sys.argv))
