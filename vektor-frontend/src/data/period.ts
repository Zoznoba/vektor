/**
 * Период кампании — год + месяц числами (бэкенд отдаёт period_year /
 * period_month). Название месяца — это ОТОБРАЖЕНИЕ, поэтому живёт здесь, а
 * не в ответе API: бэкенд отдаёт доменные данные, а готовый текст под UI
 * собирает фронт (то же решение, что по badgeLabel анкет).
 */
import type { CampaignRef } from '../types/results';

/**
 * Именительный падеж, с заглавной — «Июнь 2026».
 *
 * Не toLocaleDateString('ru-RU', { month: 'long' }): в составе даты он даёт
 * родительный падеж («20 июня»), а нам нужен месяц сам по себе.
 */
export const MONTHS_RU = [
  'Январь',
  'Февраль',
  'Март',
  'Апрель',
  'Май',
  'Июнь',
  'Июль',
  'Август',
  'Сентябрь',
  'Октябрь',
  'Ноябрь',
  'Декабрь',
] as const;

/** «Июнь 2026». Месяц вне 1–12 (битые данные) деградирует до одного года. */
export function formatPeriod(year: number, month: number): string {
  const name = MONTHS_RU[month - 1];
  return name ? `${name} ${year}` : String(year);
}

/** Варианты для <select> месяца в форме кампании. */
export const MONTH_OPTIONS = MONTHS_RU.map((label, index) => ({ value: index + 1, label }));

/**
 * Период, который экран группы открывает по умолчанию.
 *
 * Раньше «по умолчанию» решал бэкенд, и решал по-своему: без campaign_id он
 * считал профиль по нынешнему составу, сшивая последние диагностики каждого
 * ученика, — второй режим со своим составом и своей школой для сравнения.
 * Теперь правило одно и живёт здесь: САМАЯ СВЕЖАЯ кампания НЫНЕШНЕЙ когорты.
 *
 * Именно нынешней: школа переиспользует строки классов из года в год, поэтому
 * «последняя кампания класса 5-1» — это, скорее всего, дети, которые сегодня
 * учатся в 6-1. Открывать такое молча нельзя: экран выглядит рабочим, а
 * показывает чужих людей. Архив остаётся в списке и открывается явным выбором.
 *
 * `closedOnly` — для балльных экранов: по идущей кампании баллы не считаются
 * вовсе (409), а экран мониторинга, наоборот, ради неё и открывают.
 *
 * undefined — «своей диагностики у этого состава ещё не было»: у нового
 * набора это штатное состояние, и подставлять вместо него архив нельзя.
 */
export function defaultCampaignId(
  campaigns: CampaignRef[],
  options: { closedOnly?: boolean } = {},
): number | undefined {
  // Список приходит свежими сверху — первое подходящее и есть самое свежее.
  const match = campaigns.find(
    (c) => c.is_current_cohort && (!options.closedOnly || c.status === 'closed'),
  );
  return match?.campaign_id;
}
